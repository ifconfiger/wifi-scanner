/// Device vendor for the first 3 bytes of a BSSID (OUI)
struct Vendor: Hashable {
    let oui: String
    /// Full organization name registered with the IEEE
    let organization: String
    /// Short brand name for sorting and tooltips
    let brand: String
    /// Extra text the search box matches (Chinese brand name, IEEE organization)
    let searchText: String
    /// Domain used to fetch the logo; nil for unlisted brands, which show a monogram
    let domain: String?
    /// The BSSID is locally administered (virtual BSSID); the vendor is guessed from the OUI with the LA bit cleared
    let isGuess: Bool

    var tooltip: String {
        var lines = [brand]
        if organization != brand { lines.append(organization) }
        lines.append(isGuess ? String(localized: "OUI \(oui) (virtual BSSID, guessed)") : "OUI \(oui)")
        return lines.joined(separator: "\n")
    }
}

enum VendorDB {
    /// OUI → IEEE organization, from Resources/oui.tsv (generated by tools/update_oui.py)
    private static let table: [String: String] = load()

    static func lookup(bssid: String) -> Vendor? {
        let hex = bssid.uppercased().filter(\.isHexDigit)
        guard hex.count >= 6, let first = UInt8(hex.prefix(2), radix: 16) else { return nil }
        let oui = String(hex.prefix(6))
        if let org = table[oui] {
            return make(oui: oui, org: org, guess: false)
        }
        // Multi-SSID APs often derive virtual BSSIDs by flipping low bits of the first byte of the base MAC:
        // some set only the LA bit (0x02), others also 0x04/0x08 (seen: Xiaomi 50→5a, Ubiquiti 60→66). Clear them in turn and retry
        if first & 0x02 != 0 {
            for mask: UInt8 in [0x02, 0x0E] {
                let base = String(format: "%02X", first & ~mask) + oui.dropFirst(2)
                if let org = table[base] { return make(oui: base, org: org, guess: true) }
            }
        }
        return nil
    }

    private static func make(oui: String, org: String, guess: Bool) -> Vendor {
        let key = " " + normalize(org) + " "
        if let b = brands.first(where: { b in b.keys.contains { key.contains(" \($0) ") } }) {
            let name = b.zh.map { prefersChinese ? "\($0) \(b.name)" : b.name } ?? b.name
            return Vendor(oui: oui, organization: org, brand: name, searchText: "\(b.zh ?? "") \(org)",
                          domain: b.domain, isGuess: guess)
        }
        return Vendor(oui: oui, organization: org, brand: shortName(org), searchText: org, domain: nil, isGuess: guess)
    }

    /// Chinese brand names are only shown when the UI itself is Chinese
    private static let prefersChinese = Bundle.main.preferredLocalizations.first?.hasPrefix("zh") ?? false

    /// Lowercase, non-alphanumerics to spaces: "TP-LINK TECHNOLOGIES CO.,LTD." → "tp link technologies co ltd"
    private static func normalize(_ s: String) -> String {
        String(s.lowercased().map { $0.isLetter || $0.isNumber ? $0 : " " })
            .split(separator: " ")
            .joined(separator: " ")
    }

    /// Strip company suffixes to get a display name for unlisted vendors
    private static func shortName(_ org: String) -> String {
        let suffixes = [
            "co., ltd.", "co.,ltd.", "co.,ltd", "co., ltd", "co ltd", "co.,", "ltd.", "ltd", "inc.", "inc",
            "corporation", "corp.", "corp", "limited", "llc", "gmbh", "s.a.", "sas", "ag", "b.v.", ",",
        ]
        var s = org.trimmingCharacters(in: .whitespaces)
        var changed = true
        while changed {
            changed = false
            for suf in suffixes where s.lowercased().hasSuffix(suf) && s.count > suf.count + 2 {
                s = String(s.dropLast(suf.count)).trimmingCharacters(in: .whitespaces)
                changed = true
            }
        }
        return s
    }

    private static func load() -> [String: String] {
        let url = Bundle.main.url(forResource: "oui", withExtension: "tsv")
            // Under swift run / Xcode we are not inside the .app; fall back to the file in the repo
            ?? URL(fileURLWithPath: #filePath)
                .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
                .appendingPathComponent("Resources/oui.tsv")
        guard let text = try? String(contentsOf: url, encoding: .utf8) else { return [:] }
        var dict: [String: String] = [:]
        dict.reserveCapacity(41_000)
        for line in text.split(separator: "\n") {
            guard let tab = line.firstIndex(of: "\t") else { continue }
            dict[String(line[..<tab])] = String(line[line.index(after: tab)...])
        }
        return dict
    }

